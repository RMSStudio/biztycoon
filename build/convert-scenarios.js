for (const id of ['agency', 'bank']) {
  const src = fs.readFileSync(path.join(ROOT, 'scenarios', id + '.js'), 'utf8');
  const sc  = (new Function(src + ';return SCENARIO;'))();
  sc.events = EVENTS[id];   // декларативная версия вместо fn

  const json = JSON.stringify(sc, null, 2);
  const out = [
    '// ══════════════════════════════════════════════════════',
    `//  SCENARIO DATA: ${sc.name} (${sc.icon})`,
    '//  ЧИСТЫЕ ДАННЫЕ — без кода. Формат значения: строгий JSON,',
    '//  можно редактировать любым текстовым редактором.',
    '//  События — декларативные эффекты (DSL: src/scenario-loader.js).',
    '//  Godot читает этот же объект как JSON напрямую.',
    '// ══════════════════════════════════════════════════════',
    'window.SCENARIO_DATA = ' + json + ';',
    '',
  ].join('\n');
  fs.writeFileSync(path.join(ROOT, 'scenarios', id + '.data.js'), out, 'utf8');
  console.log(`✅ scenarios/${id}.data.js — ${(out.length / 1024).toFixed(1)} KB, проектов: ${sc.projects.length}, событий: ${sc.events.length}`);
}
